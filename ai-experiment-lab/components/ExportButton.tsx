"use client";

import { type BriefSection } from "@/lib/types";

interface ExportButtonProps {
  sections: BriefSection[];
  isStageMode: boolean;
}

export default function ExportButton({
  sections,
  isStageMode,
}: ExportButtonProps) {
  const handleExport = () => {
    // Build markdown content for export
    const markdown = sections
      .map((s) => `## ${s.title}\n\n${s.content}`)
      .join("\n\n---\n\n");

    const fullContent = `# AI Experiment Brief\n\nGenerated by AI Experiment Lab — bjarnbrunenberg.com\n\n---\n\n${markdown}\n\n---\n\n*Generated by AI Experiment Lab | Built by Bjarn Brunenberg*\n*This experiment brief was created using the Strategic Experimentation Framework (SEF)*`;

    // Create and download as .md file
    const blob = new Blob([fullContent], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `experiment-brief-${new Date().toISOString().slice(0, 10)}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex gap-3 justify-center mt-8">
      <button
        onClick={handleExport}
        className={`font-bold rounded-xl border border-brand-cyan/30 text-brand-cyan hover:bg-brand-cyan/10 transition-all ${
          isStageMode ? "text-lg px-8 py-3" : "text-sm px-6 py-2.5"
        }`}
      >
        Export Brief
      </button>
    </div>
  );
}
